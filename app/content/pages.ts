export function pagesOf(group: PageGroup): ContentPage[] {
  return contentPages.filter((p) => p.group === group);
}

export function findPage(group: PageGroup, slug: string): ContentPage | undefined {
  return contentPages.find((p) => p.group === group && p.slug === slug);
}

export function pageHref(page: ContentPage): string {
  return `/${page.group}/${page.slug}`;
}

export function findByKey(key: string): ContentPage | undefined {
  const [group, slug] = key.split("/");
  return contentPages.find((p) => p.group === group && p.slug === slug);
}
